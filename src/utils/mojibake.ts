const ARTIFACT_SET = new Set<string>(ARTIFACT_CHARS)
const CJK_RE = /[\u3000-\u9FFF\u3400-\u4DBF\uF900-\uFAFF\u{20000}-\u{2FFFF}]/gu

/** 表意字符统计口径（分母）；命中集合数为分子。 */
function cjkCount(text: string): number {
  return text.match(CJK_RE)?.length ?? 0
}

function artifactCount(text: string): number {
  let hits = 0
  for (const ch of text) {
    if (ARTIFACT_SET.has(ch)) hits += 1
  }
  return hits
}

export function looksLikeMojibake(text: string): boolean {
  if (!text) return false
  if (text.includes('\uFFFD')) return true
  const cjk = cjkCount(text)
  if (cjk < 2) return false
  const hits = artifactCount(text)
  if (hits < 2) return false
  return hits / cjk >= 0.6
}

export type ReadableSourceText = {
  /** 呈现文本：正常原文，或可读降级占位。 */
  text: string
  /** 判为乱码时的原文（悬停排查用），正常时为 null。 */
  raw: string | null
}

/**
 * 来源类文本的可读化：乱码 → 占位 + 原文；正常 → 原文直通。
 * null/undefined/空串按「无内容」直通（调用方自行表达空态）。
 */
export function readableSourceText(
  value: string | null | undefined,
  fallback = '来源解析失败'
): ReadableSourceText {
  if (value === null || value === undefined || value === '') return { text: value ?? '', raw: null }
  if (looksLikeMojibake(value)) return { text: fallback, raw: value }
  return { text: value, raw: null }
}
