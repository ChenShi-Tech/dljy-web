// 地图标签文案工具。

// 民族名必须显式枚举，不能用 `[一-龥]{1,3}族` 这类通配，它会贪婪吃掉地名本身：
// 「红河哈尼族彝族自治州」中 `[一-龥]{1,3}族` 会先匹配到「河哈尼族」，裁出「红」；
// 「大理白族自治州」会整体匹配「大理白族」，裁成空串。按民族名精确匹配才安全。
const ETHNIC_NAMES = [
  '维吾尔', '柯尔克孜', '乌孜别克', '鄂伦春', '鄂温克', '达斡尔', '塔吉克', '塔塔尔',
  '哈萨克', '撒拉', '仡佬', '毛南', '仫佬', '布依', '朝鲜', '土家', '哈尼', '傈僳',
  '景颇', '德昂', '独龙', '基诺', '阿昌', '保安', '裕固', '纳西', '拉祜', '东乡',
  '锡伯', '普米', '门巴', '珞巴', '赫哲', '俄罗斯', '蒙古', '布朗', '水', '畲',
  '彝', '白', '壮', '苗', '傣', '藏', '回', '侗', '瑶', '羌', '满', '黎', '佤',
  '土', '怒', '京', '高山', '塔塔尔',
]

// 长名优先，避免「哈尼」先被「哈」之类的短名截断。
const ETHNIC_PATTERN = new RegExp(
  `(?:${[...ETHNIC_NAMES].sort((a, b) => b.length - a.length).join('|')})族`,
  'g',
)

const ADMIN_SUFFIX = /(市辖区|特别行政区|自治州|自治县|自治区|地区|盟|市)$/

/**
 * 地市州简称：去掉民族名与行政后缀。
 *
 * 「西双版纳傣族自治州」→「西双版纳」，「昆明市」→「昆明」，
 * 「红河哈尼族彝族自治州」→「红河」。
 *
 * 只用于地图上的分块标签，全称在图上必然互相重叠且喧宾夺主，
 * tooltip 与选中态仍显示全称。
 */
export function shortSubdivisionName(name: string): string {
  const raw = String(name ?? '')
  const short = raw.replace(ETHNIC_PATTERN, '').replace(ADMIN_SUFFIX, '').trim()
  // 兜底：极端情况下裁成空串就退回全称，宁可挤也不能没有标签。
  return short || raw
}
