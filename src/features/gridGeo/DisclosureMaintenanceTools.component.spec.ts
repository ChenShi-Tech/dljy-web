import { mount } from '@vue/test-utils'
import { describe, expect, it } from 'vitest'
import DisclosureMaintenanceTools from './DisclosureMaintenanceTools.vue'
import { createDefaultMaintenanceFilters } from './disclosureMaintenance'

describe('检修停运专业筛选工具', () => {
  it('输入独立设备/原因关键词立即发模型更新，防抖留父页并保留其他筛选', async () => {
    const filters = { ...createDefaultMaintenanceFilters(), timingFilter: 'covers-window' as const }
    const wrapper = mount(DisclosureMaintenanceTools, { props: { modelValue: filters, windowLabel: '2026-07-01 12:00—18:00' } })
    await wrapper.find('[aria-label="搜索检修设备或电厂"]').setValue('大朝山')
    expect(wrapper.emitted('update:modelValue')?.[0]).toEqual([{ ...filters, equipmentKeyword: '大朝山' }])
    await wrapper.setProps({ modelValue: { ...filters, equipmentKeyword: '大朝山' } })
    await wrapper.find('[aria-label="搜索检修停运原因"]').setValue('检修')
    expect(wrapper.emitted('update:modelValue')?.[1]).toEqual([{ ...filters, equipmentKeyword: '大朝山', reasonKeyword: '检修' }])
    expect(filters.equipmentKeyword).toBe('')
    wrapper.unmount()
  })
  it('类别、窗口时间关系与排序值符合接口契约，历史窗口不用正在进行措辞', async () => {
    const wrapper = mount(DisclosureMaintenanceTools, { props: { modelValue: createDefaultMaintenanceFilters(), category: 'maintenance', windowLabel: '2026-07-01 全日' } })
    expect(wrapper.text()).toContain('查询窗口：2026-07-01 全日')
    expect(wrapper.text()).toContain('原因 / 摘要')
    expect(wrapper.text()).not.toContain('当前进行中')
    expect(wrapper.findAll('.categories button').map(button => button.attributes('aria-pressed'))).toEqual(['false', 'true', 'false'])
    await wrapper.findAll('.categories button')[2].trigger('click')
    expect(wrapper.emitted('update:category')?.[0]).toEqual(['outage'])
    await wrapper.find('[aria-label="检修停运时间关系"]').setValue('ends-in-window')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toMatchObject({ timingFilter: 'ends-in-window' })
    await wrapper.find('[aria-label="检修停运排序"]').setValue('duration-desc')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toMatchObject({ sort: 'duration-desc' })
    wrapper.unmount()
  })
  it('清空仅重置专业筛选和类别，窗口标签保留；所有按钮支持原生键盘操作', async () => {
    const wrapper = mount(DisclosureMaintenanceTools, { props: { modelValue: { ...createDefaultMaintenanceFilters(), reasonKeyword: '故障', sort: 'start-asc' }, category: 'outage', windowLabel: '2026-07-01 01:00—02:00' } })
    expect(wrapper.findAll('button').every(button => button.attributes('type') === 'button')).toBe(true)
    await wrapper.find('.clear').trigger('click')
    expect(wrapper.emitted('update:modelValue')?.at(-1)).toEqual([createDefaultMaintenanceFilters()])
    expect(wrapper.emitted('update:category')?.at(-1)).toEqual([''])
    expect(wrapper.emitted('clear')).toHaveLength(1)
    expect(wrapper.text()).toContain('2026-07-01 01:00—02:00')
    await wrapper.setProps({ modelValue: createDefaultMaintenanceFilters(), category: '' })
    expect(wrapper.find('.clear').attributes('disabled')).toBeDefined()
    wrapper.unmount()
  })
  it('未选主题时提供五类披露搜索和通用时间排序，不使用停复电口径', async () => {
    const wrapper = mount(DisclosureMaintenanceTools, { props: { generic: true, categories: ['maintenance', 'outage', 'intervention', 'congestion', 'constraint'], category: 'constraint', modelValue: createDefaultMaintenanceFilters(), windowLabel: '2026-07-01 全日' } })
    expect(wrapper.get('[data-testid="disclosure-tools"]').attributes('aria-label')).toBe('披露筛选')
    expect(wrapper.find('[data-testid="maintenance-tools"]').exists()).toBe(false)
    expect(wrapper.get('[role="group"]').attributes('aria-label')).toBe('披露类别')
    expect(wrapper.findAll('.categories button').map(button => button.text())).toEqual(['全部', '检修计划', '非计划停运', '人工干预', '断面阻塞', '输电约束'])
    expect(wrapper.findAll('.categories button').map(button => button.attributes('aria-pressed'))).toEqual(['false', 'false', 'false', 'false', 'false', 'true'])
    const objectInput = wrapper.get('[aria-label="搜索披露对象"]')
    expect(objectInput.attributes('placeholder')).toBe('输入电厂、设备、线路或断面名称')
    await objectInput.setValue('鲁西')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toMatchObject({ equipmentKeyword: '鲁西' })
    await wrapper.get('[aria-label="搜索披露原因或摘要"]').setValue('正向限值')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toMatchObject({ reasonKeyword: '正向限值' })
    await wrapper.findAll('.categories button')[3].trigger('click')
    expect(wrapper.emitted('update:category')?.at(-1)).toEqual(['intervention'])
    const timing = wrapper.get('[aria-label="披露时间关系"]')
    expect(timing.findAll('option').map(option => option.text())).toEqual(['全部时间关系', '窗口内开始', '窗口内结束', '贯穿所选窗口', '时间不完整'])
    await timing.setValue('ends-in-window')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toMatchObject({ timingFilter: 'ends-in-window' })
    const sort = wrapper.get('[aria-label="披露排序"]')
    expect(sort.findAll('option').map(option => option.text())).toEqual(['默认顺序', '开始时间：早 → 晚', '结束时间：早 → 晚', '已知总时长：长 → 短'])
    await sort.setValue('start-asc')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toMatchObject({ sort: 'start-asc' })
    expect(wrapper.get('.clear').text()).toBe('清空筛选')
    await wrapper.get('.clear').trigger('click')
    expect(wrapper.emitted('update:category')?.at(-1)).toEqual([''])
    expect(wrapper.emitted('update:modelValue')?.at(-1)).toEqual([createDefaultMaintenanceFilters()])
    expect(wrapper.emitted('clear')).toHaveLength(1)
    wrapper.unmount()
  })
})
